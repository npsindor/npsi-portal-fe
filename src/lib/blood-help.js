export const BLOOD_COPY = { en, hi };
export const useBloodCopy = () => {
  const { lang } = useLang();
  return { t: lang === "hi" ? hi : en, lang };
};

// A server error in the page language (known codes), else the server's own message.
export const bloodError = (error, t) => t.errors[error?.message] || error?.message || t.failed;

export const formatDay = (value, lang) => {
  if (!value) return "";
  const date = new Date(/^\d{4}-\d{2}-\d{2}$/.test(String(value)) ? `${value}T00:00:00` : value);
  return Number.isNaN(date.getTime()) ? "" : date.toLocaleDateString(lang === "hi" ? "hi-IN" : "en-IN", { day: "numeric", month: "short", year: "numeric" });
};

export const validMobile = (value) => /^[6-9]\d{9}$/.test(String(value || "").replace(/\D/g, "").slice(-10));
